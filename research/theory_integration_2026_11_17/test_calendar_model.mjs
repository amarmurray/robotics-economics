import assert from 'node:assert/strict';
import {fixedPaths,slopeAndLimit,optimal,cashBuffer,stageCompletion,jointCompletion,advanceToMatch} from './calendar_model.mjs';
const near=(a,b,eps=1e-5)=>assert.ok(Math.abs(a-b)<=eps,`${a} != ${b}`);
near(slopeAndLimit().shortQuadratic,-2.1);
near(slopeAndLimit().longDifference,5/12);
assert.ok(fixedPaths(.5).gap<0);
assert.ok(fixedPaths(10).gap>0);
assert.equal(optimal(.02).initialAction,'stop');
assert.equal(optimal(.5).initialAction,'joint');
assert.equal(optimal(2).initialAction,'A');
near(optimal(.5).values[0],.8877554975724271);
near(optimal(2).values[0],11.717939283757676);
near(cashBuffer([1.5,1.5,1.5],[0,2,2]),1.5);
near(cashBuffer([1.5,1.5,1.5,0],[0,0,0,4]),4.5);
const p=stageCompletion({T:2,B:.5});
near(p,.6138049199398234);
near(jointCompletion({T:2,B:.5}),.45118836390597356);
near(advanceToMatch({prob:p,T:2,B:.5}),.29284387368854825);
assert.equal(advanceToMatch({prob:stageCompletion({T:5,B:5}),T:5,B:0}),Infinity);
console.log('15 calendar/finance assertions passed');
