'use strict';
// Independently formulated integer-mass audit: all prices on /4096 scale.
// Purely synthetic physical history law; not a robot ROI estimator.
const assert = require('node:assert/strict');
let checks = 0;
function ck(actual, expected, msg) { checks++; assert.equal(actual, expected, msg); }
function evaluate(k, groundingBonusNumerator = 2) {
  // k = 1024 * Pr(H=0,Y=1,Z=1), 0..256; H,Y,Z are binary.
  let mass=0, clearOrder=0, lateOrder=0, contingentLate=0;
  const pair=new Map();
  for(let h=0;h<2;h++) for(let y=0;y<2;y++) for(let z=0;z<2;z++) {
    const parity = ((h+y+z)%2===0)?1:-1;
    const w=128+(k-128)*parity;
    if(w<0) throw Error('Negative physical scenario probability');
    mass+=w;
    if(h===0&&y===1) { clearOrder+=w; if(z===1)contingentLate+=w; }
    if(z===1)lateOrder+=w;
    for(const [i,j] of [[0,1],[0,2],[1,2]]) {
      const bits=[h,y,z];const key=''+i+j+bits[i]+bits[j];
      pair.set(key,(pair.get(key)||0)+w);
    }
  }
  ck(mass,1024,'total probability');
  for(const x of pair.values())ck(x,256,'all three pairwise binary distributions');
  ck(clearOrder,256,'T opportunity'); ck(lateOrder,512,'original late demand'); ck(contingentLate,k,'triple demand and queue');
  // The original service Y is eligible predispatch; T pays 3/4 in its own date
  // and creates a job that blocks date-3 service. R leaves worker free.
  const R=4*lateOrder, T=R+3*clearOrder-4*contingentLate;
  const P=Math.max(R,T);
  // Grounded service serves the same date-3 order but qualifies a 1/2 bonus
  // on the A&Z bundle; this adds value, not another physical service slot.
  const G=R+groundingBonusNumerator*contingentLate-128;
  const E=2304; // independently staffed terminal embodiment, net of cost
  return {R,T,P,G,E,k};
}
for(let k=0;k<=256;k++) {
  const v=evaluate(k);
  ck(v.R,2048,'old retained');ck(v.T,2816-4*k,'queue generated by T');
  ck(v.P,Math.max(2048,2816-4*k),'optional old policy');
  ck(v.G,1920+2*k,'licensed grounded bundle');ck(v.E,2304,'independent E');
  ck(v.P>v.E,k<128,'P > E boundary');ck(v.G>v.E,k>192,'G > E boundary');
}
const low=evaluate(0),middle=evaluate(160),high=evaluate(256);
ck(low.P>low.E&&low.E>low.G,true,'P winner');
ck(middle.E>middle.G&&middle.E>middle.P,true,'E winner');
ck(high.G>high.E&&high.E>high.P,true,'G winner');
ck(evaluate(256,0).G<2304&&evaluate(256,2).G>2304,true,'zero G support unresolved after full audit');
const cases=[evaluate(0),evaluate(128),evaluate(256)];
const infoNumerator=cases.reduce((t,v)=>t+Math.max(v.P,v.G,v.E),0);
const preBest=Math.max(...['R','T','G','E'].map(key=>cases.reduce((t,v)=>t+v[key],0)));
ck(infoNumerator,7552,'early original buyer/queue linkage report');
ck(preBest,6912,'precommitted best economic policy');
ck(infoNumerator-preBest,640,'information value on denominator 12288');
const midBest=Math.max(cases.reduce((t,v)=>t+v.P,0), cases.reduce((t,v)=>t+v.G,0), 3*2304);
ck(midBest,7168,'post-program, pre-dispatch report');
ck(infoNumerator-midBest,384,'program-timing option');
ck(midBest-preBest,256,'dispatch-timing option');
