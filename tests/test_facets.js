'use strict';
const assert=require('node:assert/strict');
const facets=require('../dashboard/facets.js');
const record={geography:'UK source; US target',system_id:'SYS-1',systems:['SYS-1','SYS-2'],embodiment:'sensor quadruped',harness:null,description:'US and robot policy code are mentioned only in prose'};
assert(facets.matches(record,{geography:'v:UK source; US target'}));
assert(!facets.matches(record,{geography:'v:US'}));
assert(!facets.matches(record,{openness:'v:robot policy code'}));
assert(facets.matches(record,{system:'v:SYS-2',harness:'missing'}));
assert(!facets.matches(record,{system:'v:SYS-3',harness:'missing'}));
assert(!facets.matches({nested:{geography:'US'}},{geography:'v:US'}));
assert(facets.matches({geography:null},{geography:'missing'}));
assert(!facets.matches({geography:'missing'},{geography:'missing'}));
assert(facets.matches({geography:'missing'},{geography:'v:missing'}));
assert(!facets.matches({layer:'robot policy code'},{openness:'v:robot policy code'}));
assert(facets.matches({schema_version:'openness-1.0',layer:'robot policy code',license:'MIT'},{openness:'v:robot policy code',license:'v:MIT'}));
assert(!facets.matches({layer:'robot policy code'},{openness:'v:robot policy code'},'openness_cards'));
assert(!facets.matches({layer:'robot policy code'},{openness:'v:robot policy code'},'not_openness_objects'));
assert(!facets.matches({schema_version:'openness-unrelated-not-a-type',layer:'robot policy code'},{openness:'v:robot policy code'}));
assert.deepEqual(facets.values(record,facets.definitions.find(d=>d.id==='system')),['SYS-1','SYS-2']);
const choices=facets.options([{value:record,key:'systems'},{value:{system_id:'SYS-1'},key:'evidence'},{value:{},key:'evidence'}],facets.definitions.find(d=>d.id==='system'));
assert.deepEqual(choices,{missing:1,values:[['SYS-1',2],['SYS-2',1]]});
assert(facets.matches(record,{}));
console.log('17 exact-field facet assertions passed.');
